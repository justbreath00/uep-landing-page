            <p>The establishment of UEP began in 2005 following a dissertation paper authored by its founding president, Dr. Ramon V. Guico III, structured around the idea of creating a world-class institution that will provide the best practices in education to students regardless of their social, cultural and financial background.</p>
            <p>From its modest beginnings in an obscure building located in the old public market, UEP has emerged into a modern architectural display along MacArthur Highway in barangay Canarvacanan set against Binalonan's pastoral backdrop.</p>
            <p>The first of three towers was inaugurated in July 2012 and houses the university's academic departments including Criminology, Hospitality and Management, Business Administration, Elementary and Secondary Education, Midwifery and Information Technology. The building can accommodate 3,000 students and includes classrooms, administrative offices, a library, and demonstration laboratories.</p>
            <p>Envisioned to be a center of learning in Pangasinan, the campus community promotes diversity among its students and ensures that each one is given the opportunity to explore interests, take part in extracurricular activities, nurture relationships, and achieve personal growth.</p>
            <p>UEP also distinguishes itself for creating a culture of learning through a well-designed campus that integrates modern conveniences with the natural beauty of its surroundings.</p>
            <p>In 2011, UEP presented its first batch of graduates with degrees in BS Information Technology, BS Business Administration, BS Hospitality and Management, and diplomas in Midwifery. The university continues to attract students from Binalonan and neighboring towns in Pangasinan through affordable and quality education.</p>
